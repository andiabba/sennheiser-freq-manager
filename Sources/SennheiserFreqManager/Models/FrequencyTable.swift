import Foundation

struct FrequencyTable {
    let name: String
    let rangeMHz: String
    private let banks: [[Int?]]

    func frequency(bank: Int, channel: Int) -> Int? {
        guard bank >= 1, bank <= banks.count,
              channel >= 1, channel <= banks[bank - 1].count else { return nil }
        return banks[bank - 1][channel - 1]
    }

    func channelCount(bank: Int) -> Int {
        guard bank >= 1, bank <= banks.count else { return 0 }
        return banks[bank - 1].count
    }

    var bankCount: Int { banks.count }

    func availableChannels(bank: Int) -> [Int] {
        guard bank >= 1, bank <= banks.count else { return [] }
        return banks[bank - 1].enumerated().compactMap { (i, f) in f != nil ? i + 1 : nil }
    }

    func lookup(frequencyKHz: Int) -> (bank: Int, channel: Int)? {
        for (bi, bank) in banks.enumerated() {
            for (ci, freq) in bank.enumerated() {
                if freq == frequencyKHz { return (bi + 1, ci + 1) }
            }
        }
        return nil
    }

    static let allRanges: [FrequencyTable] = [
        rangeA1, rangeA, rangeAS, rangeB, rangeC, rangeD, rangeE, rangeG, rangeGB, rangeC_TH, rangeTH
    ]

    static func forRange(_ name: String) -> FrequencyTable? {
        allRanges.first { $0.name == name }
    }

    static func detectRange(frequencyKHz: Int) -> FrequencyTable {
        for range in allRanges {
            if range.lookup(frequencyKHz: frequencyKHz) != nil {
                return range
            }
        }
        let mhz = Double(frequencyKHz) / 1000.0
        for range in allRanges {
            let parts = range.rangeMHz.components(separatedBy: "–")
            if parts.count == 2, let lo = Double(parts[0]), let hi = Double(parts[1]),
               mhz >= lo, mhz <= hi {
                return range
            }
        }
        return rangeA1
    }

    init(name: String, rangeMHz: String, banks: [[Int?]]) {
        self.name = name
        self.rangeMHz = rangeMHz
        self.banks = banks
    }

